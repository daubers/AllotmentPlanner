const { chromium } = require("@playwright/test");
const fs = require("node:fs");
const demo = JSON.parse(fs.readFileSync("/shots/demo.json", "utf8"));
const base = "http://frontend:5173";
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, colorScheme: "light" });
  const page = await ctx.newPage();
  await page.goto(`${base}/login`);
  await page.getByLabel("Email").fill(demo.email);
  await page.getByLabel("Password").fill(demo.password);
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("heading", { name: "Your allotments" }).waitFor();
  await page.goto(`${base}/allotments/${demo.allotment}`);
  await page.locator(".leaflet-container").waitFor();
  await page.waitForTimeout(2500);
  const panel = page.locator("aside.panel").first();
  await panel.locator("button.sighting-thumb").first().click();
  await page.waitForTimeout(1200);
  await page.locator("dialog[open]").screenshot({ path: "/shots/demo_shots/found.png" });
  await page.keyboard.press("Escape");
  const phone = await browser.newContext({ viewport: { width: 390, height: 800 }, deviceScaleFactor: 2, colorScheme: "light" });
  const pp = await phone.newPage();
  await pp.goto("http://host.docker.internal:8099/?light", { timeout: 180000 });
  await pp.getByText("Photograph the plot").first().waitFor({ timeout: 180000 });
  await pp.waitForTimeout(1200);
  await pp.screenshot({ path: "/shots/demo_shots/phone.png", clip: { x: 0, y: 0, width: 390, height: 770 } });
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
